#!/usr/bin/env python3
"""Generate data/inventory/javascript.toml.

Usage:
    python3 scripts/inventory/javascript.py --node /path/to/node [--node ...] [--check]

The orchestrating Python must be 3.11 or later (tomllib). Each `--node` binary
is probed in a subprocess and the results are merged as a union:

- `stdlib_modules`: `require("module").builtinModules`, plus the prefix-only
  builtins (`node:test`, `node:test/reporters`, `node:sea`, `node:sqlite`) that
  load under the `node:` scheme, plus `globalThis`, the ambient module.
- `members`: `Object.getOwnPropertyNames` of the exports of every module
  classified `egress` in data/primitives/javascript.toml and of every deny-list
  module, and of `globalThis` (its own properties, which are the Node ambient
  globals). Modules covered wholly by an `egress` or `blind-spot` entry whose
  ID is the module itself are skipped.

Versions of the declared range (Node 18 to 22) without a `--node` are listed in
`not_generated`. With `--check`, exits 1 if the output would differ from the
checked-in file. A development tool run outside the scanner binary.
"""

import argparse
import json
import subprocess
import sys
import tempfile
import tomllib
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
PRIMITIVES = REPO / "data" / "primitives" / "javascript.toml"
OUT = REPO / "data" / "inventory" / "javascript.toml"
RANGE = ["18", "19", "20", "21", "22"]

# Deny list; the data guard test holds its own copy.
DENY = ["module", "inspector", "dns", "repl", "wasi"]
PREFIX_ONLY = ["test", "test/reporters", "sea", "sqlite"]

PROBE = r"""
const req = JSON.parse(require("fs").readFileSync(0, "utf8"));
const out = { version: process.versions.node, stdlib: [], members: {}, failed: {} };
const builtins = new Set(require("module").builtinModules);
for (const p of req.prefixOnly) {
  try { require("node:" + p); builtins.add(p); } catch (e) { out.failed["node:" + p] = e.code || e.name; }
}
out.stdlib = [...builtins].sort();
for (const m of req.modules) {
  let v;
  try {
    v = m === "globalThis" ? globalThis : require(builtins.has(m) && req.prefixOnly.includes(m) ? "node:" + m : m);
  } catch (e) { out.failed[m] = e.code || e.name; continue; }
  out.members[m] = Object.getOwnPropertyNames(v).sort();
}
process.stdout.write(JSON.stringify(out));
"""


def wanted_modules():
    data = tomllib.loads(PRIMITIVES.read_text())
    covered = {e["id"].split(":", 1)[1] for e in data.get("entry", []) if e.get("kind") in ("egress", "blind-spot")}
    mods = {m["name"] for m in data.get("module", []) if m.get("class") == "egress"}
    mods |= set(DENY)
    mods.add("globalThis")
    return sorted(m for m in mods if m not in covered)


def probe(node, modules):
    # Run from a file, not `node -e`: eval mode adds `require`, `module`, and
    # every builtin module name to globalThis, which a real program never sees.
    with tempfile.TemporaryDirectory() as d:
        script = Path(d) / "probe.cjs"
        script.write_text(PROBE)
        r = subprocess.run(
            [node, str(script)],
            input=json.dumps({"modules": modules, "prefixOnly": PREFIX_ONLY}),
            capture_output=True,
            text=True,
            check=True,
        )
    return json.loads(r.stdout)


def q(s):
    return json.dumps(s, ensure_ascii=False)


def render(results, modules):
    versions = sorted((r["version"] for r in results), key=lambda v: [int(x) for x in v.split(".")])
    have = {v.split(".")[0] for v in versions}
    not_generated = [f"{v}: no node binary supplied" for v in RANGE if v not in have]
    stdlib = {"globalThis"}
    members, failed = {}, {}
    for r in results:
        stdlib |= set(r["stdlib"])
        for m, names in r["members"].items():
            members.setdefault(m, set()).update(names)
        for m, why in r["failed"].items():
            failed.setdefault(m, []).append(f"{r['version']} {why}")
    for m in modules:
        if m not in members:
            not_generated.append(f"module {m}: not loadable ({'; '.join(failed.get(m, []))})")
    lines = [
        "# Generated by scripts/inventory/javascript.py. Do not edit by hand.",
        f"# Probed Node versions: {', '.join(versions)}.",
        "# Versions of the declared range 18 to 22 without a binary are listed in",
        "# not_generated; their builtin modules and members are not inventoried.",
        "# globalThis is the ambient module; its members are Node's own globals.",
        "",
        'language = "javascript"',
        f"generated_from = [{', '.join(q(v) for v in versions)}]",
        "not_generated = [",
        *[f"    {q(x)}," for x in not_generated],
        "]",
        "stdlib_modules = [",
        *[f"    {q(x)}," for x in sorted(stdlib)],
        "]",
        "",
        "[members]",
    ]
    for m in sorted(members):
        lines.append(f"{q(m)} = [")
        lines.extend(f"    {q(x)}," for x in sorted(members[m]))
        lines.append("]")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--node", action="append", required=True)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    modules = wanted_modules()
    text = render([probe(n, modules) for n in args.node], modules)
    if args.check:
        if OUT.read_text() != text:
            print(f"{OUT} is out of date", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
