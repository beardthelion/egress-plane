#!/usr/bin/env python3
"""Generate data/inventory/rust.toml.

Usage:
    python3 scripts/inventory/rust.py [--sysroot PATH] [--check]

Reads the standard library source of the toolchain pinned in rust-toolchain.toml
(the `rust-src` component; install it with
`rustup component add rust-src --toolchain <channel>`). With no `--sysroot`, the
script asks `rustc +<channel> --print sysroot`.

- `stdlib_modules`: every top-level module of `std` (`pub mod` items and
  `pub use core::x` or `pub use alloc_crate::x` re-exports of modules), written
  `std::x`, plus the crate roots `core` and `alloc`.
- `members`: for every module classified `egress` in data/primitives/rust.toml,
  the public items declared at the top level of its source file: `pub` structs,
  enums, unions, traits, functions, types, constants, statics, modules, and
  macros, plus the names `pub use` brings in, with `pub use path::*` globs
  expanded from the target module's source. `#[cfg]` attributes are ignored, so
  the list is the union over every target platform. A module covered wholly by
  an `egress` or `blind-spot` entry is skipped.

This is a source-level reading, not rustdoc: items generated by macros are not
listed. A development tool run outside the scanner binary.
"""

import argparse
import re
import subprocess
import sys
import tomllib
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
PRIMITIVES = REPO / "data" / "primitives" / "rust.toml"
OUT = REPO / "data" / "inventory" / "rust.toml"
CRATES = {"std": "std", "core": "core", "alloc": "alloc", "alloc_crate": "alloc"}
INT_MODULE = re.compile(r"^[iu](8|16|32|64|128|size)$")

ITEM = re.compile(
    r"^pub\s+(?:unsafe\s+|const\s+|async\s+|extern\s+\"[^\"]*\"\s+)*"
    r"(struct|enum|union|trait|fn|type|const|static|mod|macro)\s+(?:mut\s+)?([A-Za-z_][A-Za-z0-9_]*)"
)


def channel():
    t = tomllib.loads((REPO / "rust-toolchain.toml").read_text())
    return t["toolchain"]["channel"]


def lex_blank(text):
    """Drop comments and replace string and char literals with empty ones, with
    a single left-to-right scan so each construct hides the others correctly."""
    out, i, n = [], 0, len(text)
    while i < n:
        c = text[i]
        if text.startswith("//", i):
            j = text.find("\n", i)
            i = n if j < 0 else j
        elif text.startswith("/*", i):
            depth, i = 1, i + 2
            while i < n and depth:
                if text.startswith("/*", i):
                    depth, i = depth + 1, i + 2
                elif text.startswith("*/", i):
                    depth, i = depth - 1, i + 2
                else:
                    i += 1
        elif c == "r" and re.match(r'r#*"', text[i:]) and (i == 0 or not (text[i - 1].isalnum() or text[i - 1] == "_")):
            hashes = re.match(r"r(#*)\"", text[i:]).group(1)
            end = text.find('"' + hashes, i + 2 + len(hashes))
            out.append('""')
            i = n if end < 0 else end + 1 + len(hashes)
        elif c == '"':
            i += 1
            while i < n and text[i] != '"':
                i += 2 if text[i] == "\\" else 1
            out.append('""')
            i += 1
        elif c == "'":
            m = re.match(r"'(\\(x[0-9a-fA-F]{2}|u\{[0-9a-fA-F]*\}|.)|[^\\'])'", text[i:])
            if m:
                out.append("' '")
                i += len(m.group(0))
            else:
                out.append(c)
                i += 1
        else:
            out.append(c)
            i += 1
    return "".join(out)


def strip_comments_and_attrs(text):
    """Remove comments, string literals, and attributes, keeping code shape."""
    text = lex_blank(text)
    out, i = [], 0
    while i < len(text):
        if text.startswith("#[", i) or text.startswith("#![", i):
            depth, j = 0, text.index("[", i)
            while j < len(text):
                if text[j] == "[":
                    depth += 1
                elif text[j] == "]":
                    depth -= 1
                    if depth == 0:
                        break
                j += 1
            i = j + 1
            continue
        out.append(text[i])
        i += 1
    return "".join(out)


def top_level_statements(text):
    """Yield statements at brace depth zero. A `use` tree keeps its braces; any
    other braced block is dropped, leaving only its header."""
    depth, buf = 0, []
    for ch in strip_comments_and_attrs(text):
        head = "".join(buf).lstrip()
        in_use = re.match(r"^(pub(\([^)]*\))?\s+)?use\b", head) is not None
        if depth == 0 or in_use:
            buf.append(ch)
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0 and not in_use:
                yield "".join(buf).strip()
                buf = []
        elif ch == ";" and depth == 0:
            yield "".join(buf).strip()
            buf = []


def module_file(lib, crate, path):
    base = lib / CRATES[crate] / "src"
    if not path:
        return base / "lib.rs"
    p = base.joinpath(*path)
    for cand in (p.with_suffix(".rs"), p / "mod.rs"):
        if cand.is_file():
            return cand
    return None


def split_use(tree):
    """Expand a use tree like `a::{b, c as d, e::*}` into (path, name) pairs."""
    tree = re.sub(r"\s+as\s+", "=>", tree)
    tree = re.sub(r"\s+", "", tree)
    m = re.match(r"^(.*?)\{(.*)\}$", tree)
    if not m:
        if "::" in tree:
            path, last = tree.rsplit("::", 1)
        else:
            path, last = "", tree
        return [(path, last)]
    prefix = m.group(1).rstrip(":")
    out, depth, cur = [], 0, ""
    for ch in m.group(2) + ",":
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
        if ch == "," and depth == 0:
            if cur:
                for p, n in split_use(cur):
                    out.append(((prefix + "::" + p).strip(":") if p else prefix, n))
            cur = ""
        else:
            cur += ch
    return out


def resolve(crate, modpath, usepath):
    """Resolve a use path to (crate, module path) or None."""
    parts = [p for p in usepath.split("::") if p]
    if not parts:
        return crate, modpath
    head = parts[0]
    if head == "self":
        return crate, modpath + parts[1:]
    if head == "super":
        cur = list(modpath)
        while parts and parts[0] == "super":
            cur = cur[:-1]
            parts = parts[1:]
        return crate, cur + parts
    if head == "crate":
        return crate, parts[1:]
    if head in CRATES:
        return head, parts[1:]
    return crate, modpath + parts


def members(lib, crate, path, seen=None):
    seen = seen if seen is not None else set()
    key = (CRATES[crate], tuple(path))
    if key in seen:
        return set()
    seen.add(key)
    f = module_file(lib, crate, path)
    if f is None:
        return set()
    out = set()
    for stmt in top_level_statements(f.read_text(errors="replace")):
        stmt = stmt.strip()
        stmt = re.sub(r"^pub\((crate|super|self|in [^)]*)\)\s*", "", stmt)
        m = ITEM.match(stmt)
        if m:
            out.add(m.group(2))
            continue
        u = re.match(r"^pub\s+use\s+(.*?);?$", stmt, re.S)
        if not u:
            continue
        for upath, name in split_use(u.group(1)):
            if name == "*":
                c, mp = resolve(crate, path, upath)
                out |= members(lib, c, mp, seen)
            elif name == "self":
                out.add(upath.rsplit("::", 1)[-1])
            else:
                out.add(name.split("=>")[-1])
    return out


def std_modules(lib):
    core_mods = members_of_kind(lib, "core", "mod")
    alloc_mods = members_of_kind(lib, "alloc", "mod")
    mods = set()
    for stmt in top_level_statements((lib / "std" / "src" / "lib.rs").read_text()):
        stmt = stmt.strip()
        m = ITEM.match(stmt)
        if m and m.group(1) == "mod":
            mods.add(m.group(2))
            continue
        u = re.match(r"^pub\s+use\s+(core|alloc_crate)::(.*?);?$", stmt, re.S)
        if u:
            src = core_mods if u.group(1) == "core" else alloc_mods
            for _, name in split_use(u.group(2)):
                # Integer modules are re-exported in core from a private
                # module rather than declared with `pub mod`.
                if name in src or INT_MODULE.match(name):
                    mods.add(name)
    return sorted(f"std::{m}" for m in mods) + ["alloc", "core"]


def members_of_kind(lib, crate, kind):
    out = set()
    for stmt in top_level_statements((lib / crate / "src" / "lib.rs").read_text()):
        stmt = stmt.strip()
        m = ITEM.match(stmt)
        if m and m.group(1) == kind:
            out.add(m.group(2))
    return out


def std_path(lib, name):
    """Map `std::a::b` (or `core::a`) to the crate and module path of its source."""
    parts = name.split("::")
    crate, path = parts[0], parts[1:]
    if crate == "std" and path and module_file(lib, "std", path[:1]) is None:
        for c in ("core", "alloc"):
            if module_file(lib, c, path[:1]) is not None:
                return c, path
    return crate, path


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sysroot")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    ch = channel()
    sysroot = args.sysroot or subprocess.run(
        ["rustc", f"+{ch}", "--print", "sysroot"], capture_output=True, text=True, check=True
    ).stdout.strip()
    lib = Path(sysroot) / "lib" / "rustlib" / "src" / "rust" / "library"
    if not (lib / "std" / "src" / "lib.rs").is_file():
        print(f"{lib}: rust-src is not installed for {ch}", file=sys.stderr)
        return 1
    data = tomllib.loads(PRIMITIVES.read_text())
    covered = {e["id"].split(":", 1)[1] for e in data.get("entry", []) if e.get("kind") in ("egress", "blind-spot")}
    wanted = sorted(m["name"] for m in data.get("module", []) if m.get("class") == "egress" and m["name"] not in covered)
    inv = {}
    for name in wanted:
        crate, path = std_path(lib, name)
        if not path and crate in ("core", "alloc"):
            inv[name] = sorted(members_of_kind(lib, crate, "mod"))
        else:
            inv[name] = sorted(members(lib, crate, path))
    q = lambda s: '"' + s + '"'  # noqa: E731
    lines = [
        "# Generated by scripts/inventory/rust.py. Do not edit by hand.",
        f"# Source: the rust-src component of the pinned toolchain {ch}, read at source",
        "# level with #[cfg] ignored (the union over every target platform). Items",
        "# generated by macros are not listed.",
        "",
        'language = "rust"',
        f"generated_from = [{q(ch)}]",
        "not_generated = []",
        "stdlib_modules = [",
        *[f"    {q(m)}," for m in std_modules(lib)],
        "]",
        "",
        "[members]",
    ]
    for m in sorted(inv):
        lines.append(f"{q(m)} = [")
        lines.extend(f"    {q(x)}," for x in inv[m])
        lines.append("]")
    text = "\n".join(lines) + "\n"
    if args.check:
        if OUT.read_text() != text:
            print(f"{OUT} is out of date", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
